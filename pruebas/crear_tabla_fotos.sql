-- La tabla de fotos del inventario, en la base PostGIS.
--
-- POR QUÉ SE CREA POR SQL Y NO CON `migrate`
-- ------------------------------------------
-- El router del proyecto dice allow_migrate -> False para la app
-- `inventario`, en todas las bases: el esquema de PostGIS lo gobiernan los
-- .sql de carga, no Django. Es una decisión deliberada y tiene este precio.
--
-- POR QUÉ COMO SUPERUSUARIO
-- -------------------------
-- `gis_app` es el usuario con el que entra la API y no tiene permiso de
-- creación sobre el esquema `inventario`. Está bien que no lo tenga: es
-- justo lo que evita que un fallo en la API toque el esquema. Se crea con
-- el superusuario y después se le dan a `gis_app` los permisos que necesita
-- y ninguno más.
--
--   docker compose exec -T jurp_postgis sh -c \
--     'psql -v ON_ERROR_STOP=1 -U "$POSTGRES_USER" -d jurp_gis' \
--     < crear_tabla_fotos.sql
--
-- Las columnas son EXACTAMENTE las que espera el modelo FotoActivo de
-- Django. Si alguna no cuadra, el fallo no sale al crearla: sale al guardar
-- la primera foto, en campo y con el inspector delante. Por eso después hay
-- que pasar comprobar_tabla_fotos.py, que lo verifica contra el modelo.

BEGIN;

CREATE TABLE IF NOT EXISTS inventario.inventario_foto_activo (
    id          bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tipo_activo varchar(64)  NOT NULL,
    activo_fid  integer      NOT NULL,
    imagen      varchar(100) NOT NULL,
    descripcion varchar(200) NOT NULL,
    tomada_por  varchar(120) NOT NULL,
    creada      timestamptz  NOT NULL
);

-- Se busca siempre por el par (capa, fid): es como pregunta la ficha.
CREATE INDEX IF NOT EXISTS foto_activo_tipo_fid
    ON inventario.inventario_foto_activo (tipo_activo, activo_fid);

-- Y por cada uno por separado, para los recuentos por capa.
CREATE INDEX IF NOT EXISTS foto_activo_tipo
    ON inventario.inventario_foto_activo (tipo_activo);
CREATE INDEX IF NOT EXISTS foto_activo_fid
    ON inventario.inventario_foto_activo (activo_fid);

-- Lo que la API necesita y nada más. Sin DDL: si mañana hay que cambiar
-- una columna, que vuelva a pasar por aquí alguien con permisos, que es
-- exactamente lo que se quiere de un esquema compartido.
GRANT SELECT, INSERT, UPDATE, DELETE
    ON inventario.inventario_foto_activo TO gis_app;

COMMIT;

\echo ''
\echo '── Comprobación ──'
SELECT column_name, data_type, character_maximum_length
  FROM information_schema.columns
 WHERE table_schema = 'inventario'
   AND table_name = 'inventario_foto_activo'
 ORDER BY ordinal_position;

SELECT grantee, privilege_type
  FROM information_schema.role_table_grants
 WHERE table_schema = 'inventario'
   AND table_name = 'inventario_foto_activo'
 ORDER BY grantee, privilege_type;
