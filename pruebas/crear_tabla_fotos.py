# -*- coding: utf-8 -*-
"""
Crea a mano la tabla de fotos en la base PostGIS.

    docker compose exec -T web python manage.py shell < crear_tabla_fotos.py

POR QUÉ A MANO, Y NO CON `migrate`
----------------------------------
El router de este proyecto dice, textualmente:

    def allow_migrate(self, db, app_label, ...):
        if app_label == self.app_gis:
            return False

O sea: la app `inventario` NO migra en ninguna base. Es una decisión
deliberada y razonable —el esquema de PostGIS lo gobiernan los .sql de
carga, no Django— y tiene un precio: cada tabla nueva de esa app hay que
crearla por SQL. Esto es ese precio.

También explica por qué `migrate` dijo «Applying inventario.0002_fotoactivo
OK»: Django apunta la migración como aplicada aunque el router le prohíba
ejecutar sus operaciones. La migración quedó registrada y la tabla no se
creó en ningún sitio —ni en `vigilantes` ni en `jurp_gis`—, que es justo el
caso que más despista.

LAS COLUMNAS SON LAS QUE DJANGO ESPERA, una por una. Si alguna no cuadra, el
fallo no sale aquí: sale al guardar la primera foto, en campo, con el
inspector delante. Por eso al final se comprueba contra el propio modelo en
vez de dar por bueno que el SQL estaba bien escrito.
"""

from django.db import connections

TABLA = 'inventario_foto_activo'

SQL = """
CREATE TABLE IF NOT EXISTS inventario.inventario_foto_activo (
    id          bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tipo_activo varchar(64)  NOT NULL,
    activo_fid  integer      NOT NULL,
    imagen      varchar(100) NOT NULL,
    descripcion varchar(200) NOT NULL,
    tomada_por  varchar(120) NOT NULL,
    creada      timestamptz  NOT NULL
);

-- Se busca siempre por el par (capa, fid): es como pregunta la ficha.
CREATE INDEX IF NOT EXISTS foto_activo_tipo_fid
    ON inventario.inventario_foto_activo (tipo_activo, activo_fid);

-- Y por cada uno por separado, para los recuentos por capa.
CREATE INDEX IF NOT EXISTS foto_activo_tipo
    ON inventario.inventario_foto_activo (tipo_activo);
CREATE INDEX IF NOT EXISTS foto_activo_fid
    ON inventario.inventario_foto_activo (activo_fid);
"""

print('Creando {0} en la base gis...'.format(TABLA))
with connections['gis'].cursor() as cur:
    cur.execute(SQL)
print('  SQL ejecutado.')

# ── Comprobar contra el modelo, no contra las buenas intenciones ──────────
from inventario.models import FotoActivo                      # noqa: E402

esperadas = {}
for campo in FotoActivo._meta.get_fields():
    if not getattr(campo, 'column', None):
        continue
    esperadas[campo.column] = campo.get_internal_type()

with connections['gis'].cursor() as cur:
    cur.execute("""
        SELECT column_name, data_type, character_maximum_length
          FROM information_schema.columns
         WHERE table_schema = 'inventario' AND table_name = %s
         ORDER BY ordinal_position
    """, [TABLA])
    reales = cur.fetchall()

print('\nColumnas en la base:')
for nombre, tipo, largo in reales:
    print('  {0:<12} {1}{2}'.format(
        nombre, tipo, '({0})'.format(largo) if largo else ''))

faltan = set(esperadas) - {r[0] for r in reales}
sobran = {r[0] for r in reales} - set(esperadas)
if faltan:
    print('\n[MAL] al modelo le faltan en la base: {0}'.format(sorted(faltan)))
if sobran:
    print('\n[AVISO] columnas que el modelo no conoce: {0}'.format(sorted(sobran)))

# La prueba de verdad: que el ORM pueda consultarla. Es lo que hace el
# endpoint, y es lo unico que demuestra que el router, el esquema y el
# search_path estan de acuerdo.
try:
    n = FotoActivo.objects.count()
    print('\n[OK] el ORM la lee: {0} foto(s) guardadas'.format(n))
except Exception as e:                                        # noqa: BLE001
    print('\n[MAL] el ORM todavia no la lee: {0}'.format(e))
